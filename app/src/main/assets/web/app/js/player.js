// Single player instance per visit; screens only open/dock/control. Parts: player-*.js; state: FT.playerCore.
(() => {
const P = FT.playerCore;
let audioOnly = false;

const resetStage = () => {
    audioOnly = false;
    P.stage().classList.remove('audio-only');
};

FT.player = {
    ...P.controls,
    get current() { return P.current; },
    isFullscreen: P.isFullscreen,
    expand: P.dock.expand,
    dock: P.dock.set,
    dismissMini: P.dock.dismiss,

    // Open from /api/v1/video; no-op if already loaded.
    async open(service, info) {
        if (P.current && P.current.url === info.url) return;
        P.upNext.cancel();
        P.danmaku.stop();
        P.progress.report();
        P.progress.reset();
        const owner = { service, url: info.url, info, chapters: info.chapters || [], segments: [], chapterTrack: false };
        P.current = owner;
        resetStage();
        P.stream.reset();
        P.segments.reset();
        // null if superseded
        const start = async (way) => {
            if (P.current !== owner || !(await P.build.build(info, way, owner))) return null;
            const p = P.media();
            for (const sub of info.subtitles || []) {
                p.append(P.track('subtitles', sub.isAutoGenerated ? FT.t('subtitle_auto', { name: sub.displayName }) : sub.displayName, sub.languageTag || 'en', sub.url, false));
            }
            // seek-bar preview: WebVTT storyboard track (404 when absent)
            if (!info.playback.liveRoom && !info.isLive) p.append(P.track('metadata', 'thumbnails', 'en', `/thumbnails?serviceId=${service}&id=${FT.enc(info.url)}`, true));
            if (way.tag === 'hlsjs-video' && !way.live) p.source = { src: way.src, engine: { hlsJs: P.stream.HLS_SETTINGS } };
            else p.src = way.src;
            return p;
        };
        const way = await P.stream.plan(info, service);
        const p = await start(way);
        if (!p) return;
        if (way.local) {
            const media = P.tree.media;
            media.addEventListener('error', async () => {
                if (P.current !== owner || P.tree.media !== media) return;
                FT.toast(FT.t('download_not_playable'));
                const replay = await start(await P.stream.plan(info, service, false));
                if (replay) P.progress.resume(owner, replay, info, service);
            }, { once: true });
        }
        P.build.publishMediaSession(info);
        P.progress.resume(owner, p, info, service);
        P.segments.load(service, info);
        if (info.playback.liveRoom) P.danmaku.start('/live_chat?room=' + info.playback.liveRoom, true);
        else if (service === 5) P.danmaku.start(`/danmaku?serviceId=${service}&id=${FT.enc(info.url)}`);
        P.dock.set(P.dockMode === 'off' ? 'full' : P.dockMode);
    },

    close() {
        P.upNext.cancel();
        P.danmaku.stop();
        P.progress.report();
        P.build.teardown();
        P.current = null;
        resetStage();
        document.body.classList.remove('remote-fs');
        P.dock.set('off');
    },

    // Hides video behind artwork; stream continues.
    toggleAudioOnly() {
        if (!P.current) return false;
        audioOnly = !audioOnly;
        P.stage().classList.toggle('audio-only', audioOnly);
        FT.$('#audio-art-title').textContent = audioOnly ? P.current.info.title : '';
        return audioOnly;
    },

    setDanmaku: P.danmaku.set,
    toggleDanmaku: P.danmaku.toggle,

    get upNextActive() { return P.upNext.active(); },
    upNextBack: P.upNext.back,

    setQuality: P.stream.setQuality,
    stepChapter: P.segments.step,
    jumpChapter: P.segments.jump,
    skip: P.segments.skip,
    hasSkip: P.segments.hasSkip,
};

// Fullscreen ↔ landscape lock.
document.addEventListener('fullscreenchange', () => {
    if (!P.current || !screen.orientation) return;
    if (document.fullscreenElement) { if (screen.orientation.lock) screen.orientation.lock('landscape').catch(() => {}); }
    else if (screen.orientation.unlock) screen.orientation.unlock();
});
FT.$('#skip-btn').addEventListener('click', () => FT.player.skip());
})();

package io.github.aedev.flow.localserver

import okhttp3.Request
import org.schabi.newpipe.extractor.stream.SubtitlesStream

internal fun RequestContext.handleSubtitlesProxy(
    reply: Reply,
    params: Query,
) {
    val serviceId = getServiceId(params)
    val lang = params["lang"]
    val isAuto = "true" == params["auto"]
    val info = source.streamInfo(serviceId, params["id"] ?: throw BadRequestException("Missing 'id' parameter"))

    val subs: List<SubtitlesStream> =
        try {
            info.subtitles
        } catch (_: Exception) {
            emptyList()
        }
    val target = subs.firstOrNull { it.languageTag == lang && it.isAutoGenerated == isAuto } ?: subs.firstOrNull { it.languageTag == lang }
    if (target == null) {
        reply.send(404, "Subtitles not found", "text/plain; charset=UTF-8")
        return
    }

    val vttUrl = target.content.replace(Regex("&fmt=[^&]*"), "") + "&fmt=vtt"
    val request =
        Request
            .Builder()
            .url(vttUrl)
            .header("User-Agent", "Mozilla/5.0")
            .build()
    LocalServerCaches.httpClient.newCall(request).execute().use { response ->
        val body = (response.body?.string() ?: "").withoutCueSettings().toByteArray(Charsets.UTF_8)
        reply.sendBytes(200, body, "text/vtt; charset=UTF-8", mapOf("Access-Control-Allow-Origin" to "*"))
    }
}

/** Drops cue settings ("align:start position:0%"): captions pinned left; without → centred. */
private fun String.withoutCueSettings(): String = replace(Regex("""^(\S+ --> \S+)[ \t]+\S.*$""", RegexOption.MULTILINE), "$1")

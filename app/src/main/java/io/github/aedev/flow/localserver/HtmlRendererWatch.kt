/**
 * The watch page (video and audio) and its comments. These pages carry no script of their own: the facts a script needs go out as a
 * JSON block (`#watch-config`, `#audio-config`), and js/player.js sets everything up from it.
 */
object HtmlRendererWatch {
    private fun formatChapterTimestamp(totalSeconds: Int): String {
        val h = totalSeconds / 3600
        val m = (totalSeconds % 3600) / 60
        val s = totalSeconds % 60
        return if (h > 0) "%d:%02d:%02d".format(h, m, s) else "%d:%02d".format(m, s)
    }

    /** The description as it goes into its box: plain text is escaped, HTML is left as it is, and stray blank lines at the ends dropped. */
    private fun descriptionHtml(info: StreamInfo): String {
        val description = info.description ?: return "No description provided."
        val content = description.content?.trim().orEmpty().ifEmpty { return "No description provided." }
        return if (description.type == Description.PLAIN_TEXT) WebUi.esc(content) else content
    }

    /** The related list, shared by the video page (opening videos) and the audio page (opening their audio). */
    private fun relatedList(
        info: StreamInfo,
        serviceId: Int,
        path: String,
    ): String {
        val sb = StringBuilder()
        for (related in info.relatedItems) {
            val stream = related as? StreamInfoItem
            val meta =
                if (stream != null) {
                    val views = if (stream.viewCount >= 0) "${HtmlRendererCommon.formatCount(stream.viewCount)} views" else "Live"
                    "$views • ${HtmlRendererCommon.formatUploadDate(stream.uploadDate, stream.textualUploadDate ?: "")}"
                } else {
                    ""
                }
            sb.append(
                WebUi.compactCard(
                    "$path?serviceId=$serviceId&id=${related.url}",
                    HtmlRendererCommon.getThumbnailUrl(related.thumbnailUrl),
                    related.name.orEmpty(),
                    stream?.uploaderName ?: related.name.orEmpty(),
                    meta,
                ),
            )
        }
        return sb.toString()
    }

    /** The page frame; the video itself arrives as a fragment (see [renderWatchContent]) so the page appears at once. */
    @JvmStatic
    fun renderWatchSkeleton(
        serviceId: Int,
        mediaUrl: String?,
        isTv: Boolean,
    ): String {
        val content =
            if (mediaUrl == null) {
                WebUi.notice("No video selected.", error = true)
            } else {
                WebUi.asyncRegion("/watch-content?serviceId=$serviceId&id=${WebUi.enc(mediaUrl)}", "Loading video streams...")
            }
        val body = WebShell.header(serviceId, "") + "<main class=\"container\">\n$content</main>\n"
        return WebShell.page("Loading video...", body, isTv, needsPlayer = true)
    }


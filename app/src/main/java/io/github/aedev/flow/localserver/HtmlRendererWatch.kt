    /**
     * A page of comments, or of replies: a fragment that is injected. It ends with its own "load more" (which the next page replaces),
     * so a thread can be extended as far as the server has pages.
     */
    @JvmStatic
    fun renderComments(
        serviceId: Int,
        videoUrl: String,
        items: List<CommentsInfoItem>,
        nextPage: Page?,
        isTv: Boolean,
        isReplies: Boolean = false,
    ): String {
        val base = "/comments?serviceId=$serviceId&id=${WebUi.enc(videoUrl)}"
        val context = if (isReplies) "&context=replies" else ""
        val sb = StringBuilder()
        if (items.isEmpty()) sb.append(WebUi.notice("No comments yet."))

        for (item in items) {
            val author = item.uploaderName.orEmpty()
            val avatarUrl = item.uploaderAvatarUrl?.takeIf { HtmlRendererCommon.hasThumbnail(it) }
            val time = HtmlRendererCommon.formatUploadDate(item.uploadDate, item.textualUploadDate ?: "")
            val likes = if (item.likeCount > 0) HtmlRendererCommon.formatCount(item.likeCount.toLong()) else ""
            val verified = if (item.isUploaderVerified) "<span class=\"material-symbols-rounded comment-verified\" title=\"Verified\">check_circle</span>" else ""

            sb.append("<div class=\"comment\">\n")
              .append("  ${WebUi.avatar(author, avatarUrl, "sm")}\n")
              .append("  <div class=\"comment-details\">\n")
              .append("    <div class=\"comment-header\"><span class=\"comment-author\">${WebUi.esc(author)}$verified</span><span class=\"comment-time\">${WebUi.esc(time)}</span></div>\n")
            if (item.isPinned) sb.append("    <div class=\"comment-pinned\">${WebUi.icon("push_pin")}Pinned</div>\n")
            // Description.content is HTML from the extractor, and is rendered as it is.
            sb.append("    <div class=\"comment-text\">${item.commentText.content.orEmpty()}</div>\n")
            if (likes.isNotEmpty() || item.isHeartedByUploader) {
                sb.append("    <div class=\"comment-meta\">")
                if (likes.isNotEmpty()) sb.append("<span class=\"comment-like\">${WebUi.icon("thumb_up")}${WebUi.esc(likes)}</span>")
                if (item.isHeartedByUploader) sb.append("<span class=\"comment-hearted\" title=\"Hearted by creator\">${WebUi.icon("favorite")}</span>")
                sb.append("</div>\n")
            }
            val replies = item.replies
            if (item.replyCount > 0 && replies != null) {
                HtmlRendererCommon.serializePage(replies)?.let { token ->
                    sb.append("    <button type=\"button\" class=\"comment-replies-toggle\" data-action=\"toggle-replies\" data-url=\"${WebUi.esc("$base&nextPage=${WebUi.enc(token)}&context=replies")}\">")
                      .append("<span class=\"material-symbols-rounded reply-chevron\">expand_more</span>${item.replyCount} replies</button>\n")
                      .append("    <div class=\"comment-replies\"></div>\n")
                }
            }
            sb.append("  </div>\n</div>\n")
        }

        val next = HtmlRendererCommon.serializePage(nextPage)?.let { "$base&nextPage=${WebUi.enc(it)}$context" }
        sb.append(WebUi.loadMore(next, if (isReplies) "Load more replies" else "Load more comments"))
        return sb.toString()
    }

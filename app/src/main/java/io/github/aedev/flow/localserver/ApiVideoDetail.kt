/** Watch page: card fields + description, related, playback proxy URLs (`/stream`, `/hlsvod`, `/subtitles`), chapters. */
internal fun StreamInfo.toDetail(serviceId: Int): VideoDetail {
    val encodedUrl = WebFormat.encodeUrl(url)
    return VideoDetail(
        id = LocalServerMedia.getVideoId(url),
        url = url ?: "",
        serviceId = serviceId,
        title = name ?: "",
        channelName = uploaderName ?: "",
        channelId = uploaderUrl ?: "",
        thumbnailUrl = WebFormat.getThumbnailUrl(thumbnails),
        channelThumbnailUrl =
            if (WebFormat.hasThumbnail(
                    uploaderAvatars,
                )
            ) {
                sameOriginImageUrl(WebFormat.getThumbnailUrl(uploaderAvatars))
            } else {
                ""
            },
        duration = duration.coerceAtLeast(0).toInt(),
        viewCount = viewCount.coerceAtLeast(-1),
        likeCount = likeCount.coerceAtLeast(0),
        uploadDate = textualUploadDate ?: "",
        description = description?.content ?: "",
        descriptionType = if (description?.type == Description.HTML) "html" else "text",
        isLive = streamType == StreamType.LIVE_STREAM || streamType == StreamType.AUDIO_LIVE_STREAM,
        isShort = duration in 1..SHORT_MAX_SECONDS,
        relatedVideos = relatedItems.orEmpty().filterIsInstance<StreamInfoItem>().map { it.toVideoCard() },
        playback = playback(serviceId, encodedUrl),
        subtitles = subtitleTracks(serviceId, encodedUrl),
        chapters =
            streamSegments.orEmpty().map {
                ChapterDto(
                    it.startTimeSeconds,
                    it.title ?: "",
                    it.previewUrl.takeUnless(String?::isNullOrBlank)?.let(WebFormat::getThumbnailUrl) ?: "",
                )
            },
    )
}

private fun StreamInfo.playback(
    serviceId: Int,
    encodedUrl: String,
): PlaybackDto {
    // ladder = video-only streams; combined-only video: no HLS rungs
    val hasLadder = StreamCatalog.of(InfoStreams(this), highest = true).videos.isNotEmpty()
    val hasVideo = hasLadder || !hlsUrl.isNullOrEmpty()
    val bilibiliLive = LocalServerBilibili.isBilibili(serviceId) && streamType == StreamType.LIVE_STREAM && !hlsUrl.isNullOrEmpty()
    // Progressive (muxed) streams, direct `/stream?itag=`; plus the highest-bitrate audio-only entry.
    val progressive =
        videoStreams.filterNot { it.isVideoOnly }.map {
            FormatDto(it.itag, "video", it.resolution ?: "", it.format?.suffix ?: "", it.bitrate)
        }
    val audio =
        audioStreams
            ?.maxByOrNull { it.averageBitrate }
            ?.let {
                listOf(FormatDto(it.itag, "audio", "", it.format?.suffix ?: "", it.averageBitrate))
            }.orEmpty()
    return PlaybackDto(
        isAdaptive = hasVideo && !bilibiliLive,
        // Room playlist via relay: CDN needs a Referer browsers cannot send.
        hlsUrl = if (bilibiliLive) hlsRelayPath(hlsUrl.orEmpty()) else null,
        liveRoom = if (bilibiliLive) id else null,
        qualities = downloadQualities(videoStreams.orEmpty() + videoOnlyStreams.orEmpty()).map { QualityDto(it.height, it.codecs) },
        playlistUrl = "/hlsvod?serviceId=$serviceId&id=$encodedUrl",
        streamUrl = "/stream?serviceId=$serviceId&id=$encodedUrl",
        formats = progressive + audio,
    )
}

private fun StreamInfo.subtitleTracks(
    serviceId: Int,
    encodedUrl: String,
): List<SubtitleDto> =
    try {
        subtitles.orEmpty().map {
            SubtitleDto(
                it.languageTag ?: "",
                it.displayLanguageName ?: it.languageTag ?: "",
                it.isAutoGenerated,
                "/subtitles?serviceId=$serviceId&id=$encodedUrl&lang=${WebFormat.encodeUrl(
                    it.languageTag ?: "",
                )}&auto=${it.isAutoGenerated}",
            )
        }
    } catch (e: Exception) {
        // info.subtitles throws without captions
        emptyList()
    }
